def _agent_id(key: str) -> str:
    return "ag_" + key


def build_agents() -> List[Dict[str, Any]]:
    """把定义转成 agent_store 能直接 save 的记录。

    M24：每条都带 when_to_use / inputs_contract / outputs_contract。
    这是参考 WorkBuddy 内置技能的定义范式——技能不只给名字和提示词，
    还要写清「什么时候该点它」「要给什么」「会拿到什么」，用户才不用靠猜。
    adapter_type 可被单条覆盖：接知识库的查证类要挂 llm_retrieval 才走 RAG。
    M25：system_prompt 由 compose_system_prompt() 统一加平台硬规则，
    单一来源，改一处全生效；hard_rules_version 供验收脚本核对版本。
    M26：web_fetch_top 由单条技能决定要不要抓网页正文（竞品调研要，
    其余只要摘要，省一次请求也少一堆噪音）。
    """
    out: List[Dict[str, Any]] = []
    for i, d in enumerate(PUBLIC_SKILLS):
        out.append({
            "agent_id": _agent_id(d["key"]),
            "name": d["name"],
            "description": d["description"],
            "when_to_use": d.get("when_to_use", ""),
            "inputs_contract": d.get("inputs_contract", ""),
            "outputs_contract": d.get("outputs_contract", ""),
            "adapter_type": d.get("adapter_type", "llm"),
            "web_fetch_top": int(d.get("web_fetch_top") or 0),
            "system_prompt": compose_system_prompt(d["system_prompt"]),
            "hard_rules_version": HARD_RULES_VERSION,
            "scope": "global",
            # 可见性判据读这个字段（M19/M20 踩过：只写 scope 会对员工隐身）
            "knowledge_scope": "global",
            "status": "published",
            "category": "public",
            "category_cn": "公共库",
            "sub_function": d["sub_function"],
            "tags": d["tags"],
            "public": True,
            "default_format": d["default_format"],
            # 排序位：前端按它排，不依赖名称拼音
            "sort": i,
            "registered_by": "system",
        })
    return out


def groups() -> List[Dict[str, Any]]:
    """按组给前端（写作/演示/表格/沟通/阅读），组内保定义顺序。"""
    out: List[Dict[str, Any]] = []
    for g in PUBLIC_GROUPS:
        items = [d for d in PUBLIC_SKILLS if d["sub_function"] == g]
        if items:
            out.append({"sub_function": g, "count": len(items)})
    return out
